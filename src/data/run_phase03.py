"""Run Phase 3: clean the survey, build the targets and write the documentation tables.

    python -m src.data.run_phase03

Outputs:
    data/interim/survey_labeled.csv   cleaned data with targets (not committed: row-level data)
    reports/phase03/*.csv             cleaning log, class counts, missing values, role table
    docs/data_dictionary.md           generated data dictionary
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import pandas as pd

from src.data.clean import clean_survey, missing_summary
from src.data.labels import class_counts, make_labels, small_classes
from src.data.load import column_specs, load_raw
from src.utils.config import load_config, resolve_path
from src.utils.logging_setup import get_logger

logger = get_logger(__name__)

TARGET_COLUMNS = [
    "university_group",
    "degree_category",
    "goal_status",
    "target_combination_observed",
]
DERIVED_MEANINGS = {
    "university_group": "University grouped by region (configs/labels.yaml)",
    "degree_category": "Degree programme grouped into the form's target categories",
    "target_category": "Degree aimed for at the start of A/L, as a degree category",
    "goal_status": "Target category reached or not (not a model target)",
    "target_combination_observed": (
        "1 = someone in the data reached the target category with the same A/L subjects; "
        "0 = nobody did (data-derived check, not an admission rule)"
    ),
    "al_subject_combination": "A/L subjects taken (grades not used)",
}


def role_table(roles: dict[str, Any], data: pd.DataFrame) -> pd.DataFrame:
    """Return one row per raw column with its role, reason and missing count."""
    specs = {s["name"]: s for s in column_specs()}
    rows = []
    for name, info in roles["columns"].items():
        rows.append(
            {
                "column": name,
                "question": specs[name]["label"] if name in specs else "",
                "role": info["role"],
                "reason": info["reason"],
                "missing": int(data[name].isna().sum()) if name in data else "",
            }
        )
    return pd.DataFrame(rows)


def _describe_values(series: pd.Series) -> str:
    """Short description of a column's values for the data dictionary."""
    if series.nunique() == len(series):
        return f"unique per row ({series.iloc[0]} to {series.iloc[-1]})"
    if pd.api.types.is_numeric_dtype(series) and series.nunique() > 12:
        return f"{series.min():.4g} to {series.max():.4g}"
    values = series.dropna().astype(str).value_counts()
    shown = "; ".join(f"{v} ({c})" for v, c in values.head(12).items())
    return shown + ("; ..." if len(values) > 12 else "")


def data_dictionary(data: pd.DataFrame, roles: dict[str, Any]) -> str:
    """Return the data dictionary of the labelled table as Markdown."""
    specs = {s["name"]: s for s in column_specs()}
    role_of = {k: v["role"] for k, v in roles["columns"].items()}
    lines = [
        "# Data dictionary",
        "",
        "Generated by `python -m src.data.run_phase03` from `configs/columns.yaml`, "
        "`configs/roles.yaml` and the cleaned data (`data/interim/survey_labeled.csv`, "
        f"{len(data)} rows). Values show the answer and its count.",
        "",
        "| Column | Question / meaning | Type | Role | Missing | Values |",
        "|---|---|---|---|---|---|",
    ]
    for column in data.columns:
        if column in specs:
            meaning, kind = specs[column]["label"], specs[column]["form_type"]
        elif column.endswith("_skipped"):
            meaning, kind = f"1 = '{column[:-8]}' left blank", "derived 0/1"
        elif column.endswith("_other_text"):
            meaning, kind = "1 = write-in text present", "derived 0/1"
        elif column in DERIVED_MEANINGS:
            meaning, kind = DERIVED_MEANINGS[column], "derived"
        elif column == "respondent_id":
            meaning, kind = "Anonymous ID from row order", "text"
        else:
            meaning, kind = "1 = option ticked (" + column.split("_", 1)[1] + ")", "derived 0/1"
        role = role_of.get(column) or _derived_role(column, roles)
        values = _describe_values(data[column]).replace("|", "/")
        missing = int(data[column].isna().sum())
        lines.append(f"| `{column}` | {meaning} | {kind} | {role} | {missing} | {values} |")
    return "\n".join(lines) + "\n"


def _derived_role(column: str, roles: dict[str, Any]) -> str:
    """Look up the role of a derived column from the wildcard patterns in roles.yaml."""
    derived = roles["derived"]
    if column in derived:
        return derived[column]["role"]
    for pattern, info in derived.items():
        if pattern.startswith("*") and column.endswith(pattern[1:]):
            return info["role"]
        if pattern.endswith("*") and column.startswith(pattern[:-1]):
            return info["role"]
    return "derived"


def main() -> int:
    """Clean, label and document the main survey."""
    paths = load_config("project")["paths"]
    out = resolve_path(paths["reports"]) / "phase03"
    out.mkdir(parents=True, exist_ok=True)
    roles = load_config("roles")
    labels_cfg = load_config("labels")

    raw = load_raw("survey")
    clean, log = clean_survey(raw, column_specs(), load_config("cleaning"))
    labelled = make_labels(clean, labels_cfg)

    interim = resolve_path(paths["interim"]) / "survey_labeled.csv"
    labelled.to_csv(interim, index=False, encoding="utf-8")
    log.to_csv(out / "cleaning_log.csv", index=False)
    missing_summary(labelled).to_csv(out / "missing_values.csv")
    role_table(roles, raw).to_csv(out / "column_roles.csv", index=False)

    counts = class_counts(labelled, TARGET_COLUMNS)
    counts.to_csv(out / "class_counts.csv", index=False)
    targets_only = counts[counts["target"] != "goal_status"]
    small = small_classes(targets_only, labels_cfg["small_class_rule"]["min_class_size"])
    small.to_csv(out / "small_classes.csv", index=False)
    pd.crosstab(labelled["degree_category"], labelled["al_subject_combination"]).to_csv(
        out / "degree_category_by_subject_combination.csv"
    )
    pd.crosstab(labelled["al_target_degree"], labelled["degree_category"]).to_csv(
        out / "target_degree_by_degree_category.csv"
    )
    pd.crosstab(labelled["university"], labelled["university_group"]).to_csv(
        out / "university_by_group.csv"
    )
    Path(resolve_path(paths["docs"]) / "data_dictionary.md").write_text(
        data_dictionary(labelled, roles), encoding="utf-8"
    )
    logger.info("Cleaning log entries: %d; small classes: %d", len(log), len(small))
    logger.info("Wrote %s (%d rows x %d columns)", interim.name, *labelled.shape)
    return 0


if __name__ == "__main__":
    sys.exit(main())
