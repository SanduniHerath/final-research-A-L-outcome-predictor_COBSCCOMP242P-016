"""Write SPSS-ready and SmartPLS-ready files for the Likert items (Phase 1).

The researcher runs SPSS and SmartPLS herself; these files make that a matter of
opening the file and running the supplied syntax. Exports contain row-level survey
answers, so they are written under ``data/processed`` (never committed to Git).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from src.data.load import ID_COLUMN, column_specs

# Background variables included so group comparisons are possible in SPSS.
SPSS_BACKGROUND = ["gender", "al_exam_year", "ol_school_type"]


def option_codes(name: str) -> dict[str, int]:
    """Return ``{option text: code}`` (1, 2, 3, ...) in the order the form lists the options."""
    spec = next(c for c in column_specs() if c["name"] == name)
    return {option: code for code, option in enumerate(spec["options"], start=1)}


def spss_frame(data: pd.DataFrame, likert: list[str], ratings: list[str]) -> pd.DataFrame:
    """Return the numeric SPSS table: ID, coded background variables, raw item scores.

    Item scores are exported as answered (not reverse-coded); the SPSS syntax does the
    reversal so the step is visible in SPSS output too.
    """
    table = pd.DataFrame({ID_COLUMN: data[ID_COLUMN]})
    for name in SPSS_BACKGROUND:
        table[name] = data[name].astype(str).map(option_codes(name))
    for name in likert + ratings:
        table[name] = data[name].astype("Int64")
    return table


def spss_dictionary(likert: list[str], ratings: list[str]) -> pd.DataFrame:
    """Return the data dictionary for the SPSS file (one row per variable)."""
    specs = {c["name"]: c for c in column_specs()}
    rows: list[dict[str, Any]] = [
        {
            "variable": ID_COLUMN,
            "label": "Respondent ID assigned from row order (no personal information)",
            "type": "string",
            "measure": "nominal",
            "values": "",
            "missing": "none",
        }
    ]
    for name in SPSS_BACKGROUND:
        codes = option_codes(name)
        rows.append(
            {
                "variable": name,
                "label": specs[name]["label"],
                "type": "numeric",
                "measure": "ordinal" if name == "al_exam_year" else "nominal",
                "values": "; ".join(f"{code} = {text}" for text, code in codes.items()),
                "missing": "none",
            }
        )
    for name in likert + ratings:
        anchors = (
            "1 = Strongly disagree ... 5 = Strongly agree"
            if name in likert
            else "1 = Very Low ... 5 = Very High"
        )
        rows.append(
            {
                "variable": name,
                "label": specs[name]["label"],
                "type": "numeric",
                "measure": "ordinal",
                "values": anchors,
                "missing": "none",
            }
        )
    return pd.DataFrame(rows)


def _spss_quote(text: str) -> str:
    """Quote a label for SPSS syntax (double any apostrophes, cap at 250 characters)."""
    return "'" + text.replace("'", "''")[:250] + "'"


def spss_syntax(
    csv_name: str,
    dictionary: pd.DataFrame,
    constructs: dict[str, list[str]],
    reverse: list[str],
    n_factors: int,
) -> str:
    """Return SPSS syntax that reads the CSV, labels it, reverse-codes and runs the analyses."""
    numeric = dictionary.loc[dictionary["type"] == "numeric", "variable"].tolist()
    lines = [
        "* Phase 1 questionnaire validation - generated by src/data/exports.py.",
        "* 1. Change the path on the next line to where you saved the CSV file.",
        "FILE HANDLE src",
        f"  /NAME='C:\\AL_outcome_predictor\\data\\processed\\phase01_exports\\{csv_name}'.",
        "GET DATA /TYPE=TXT /FILE=src /ENCODING='UTF8' /DELIMITERS=','",
        "  /ARRANGEMENT=DELIMITED /FIRSTCASE=2 /VARIABLES=",
        f"  {ID_COLUMN} A8",
        *[f"  {name} F2.0" for name in numeric],
        ".",
        "DATASET NAME phase01 WINDOW=FRONT.",
        "",
        "VARIABLE LABELS",
    ]
    label_lines = [f"  {row.variable} {_spss_quote(row.label)}" for row in dictionary.itertuples()]
    lines += ["\n /".join(label_lines) + "."]
    lines.append("VALUE LABELS")
    value_blocks = []
    for row in dictionary.itertuples():
        if row.variable in SPSS_BACKGROUND:
            pairs = [p.split(" = ", 1) for p in row.values.split("; ")]
            value_blocks.append(
                f"  {row.variable} " + " ".join(f"{c} {_spss_quote(t)}" for c, t in pairs)
            )
    likert_vars = " ".join(v for items in constructs.values() for v in items)
    value_blocks.append(
        f"  {likert_vars} 1 'Strongly disagree' 2 'Disagree' 3 'Neutral' 4 'Agree' "
        "5 'Strongly agree'"
    )
    lines += ["\n /".join(value_blocks) + "."]
    levels = []
    for measure in ("nominal", "ordinal"):
        names = dictionary.loc[
            (dictionary["type"] == "numeric") & (dictionary["measure"] == measure), "variable"
        ]
        if not names.empty:
            levels.append(" ".join(names) + f" ({measure.upper()})")
    lines.append("VARIABLE LEVEL " + "\n /".join(levels) + ".")
    lines += ["", "* 2. Reverse-code negatively worded items."]
    for name in reverse:
        lines.append(f"RECODE {name} (1=5) (2=4) (3=3) (4=2) (5=1) INTO {name}_r.")
        lines.append(f"VARIABLE LABELS {name}_r '{name} reverse-coded'.")
    lines.append("EXECUTE.")
    lines += ["", "* 3. Reliability per construct (Cronbach's alpha, item-total statistics)."]
    for construct, items in constructs.items():
        used = " ".join(f"{i}_r" if i in reverse else i for i in items)
        lines += [
            f"RELIABILITY /VARIABLES={used}",
            f"  /SCALE('{construct}') ALL /MODEL=ALPHA",
            "  /STATISTICS=DESCRIPTIVE SCALE CORR /SUMMARY=TOTAL.",
        ]
    all_items = " ".join(f"{i}_r" if i in reverse else i for v in constructs.values() for i in v)
    lines += [
        "",
        "* 4. KMO, Bartlett and exploratory factor analysis",
        "* (principal axis factoring, oblimin rotation).",
        "* SPSS uses Pearson correlations; the Python report also gives Spearman-based results.",
        f"FACTOR /VARIABLES {all_items}",
        "  /PRINT INITIAL KMO AIC EXTRACTION ROTATION",
        "  /FORMAT SORT",
        f"  /CRITERIA FACTORS({n_factors}) ITERATE(100)",
        "  /EXTRACTION PAF /ROTATION OBLIMIN",
        "  /PLOT EIGEN.",
    ]
    return "\n".join(lines) + "\n"


def smartpls_frame(scored: pd.DataFrame, constructs: dict[str, list[str]]) -> pd.DataFrame:
    """Return indicator columns only, with reverse-coded items already reversed.

    Args:
        scored: Item scores after reverse coding; reversed columns keep their names here and
            are renamed with a ``_r`` suffix by the caller.
        constructs: Construct to item mapping (defines column order).
    """
    order = [item for items in constructs.values() for item in items]
    return scored[order].astype(int)


def write_csv(frame: pd.DataFrame, path: Path) -> Path:
    """Write a CSV (UTF-8, no index) and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(path, index=False, encoding="utf-8")
    return path
